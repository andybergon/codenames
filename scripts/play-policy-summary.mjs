import { readFile, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const DEFAULT_REPORT_PATH = resolve(
  ROOT,
  "scripts/generated/play-policy-benchmark.json",
);
const DEFAULT_SUMMARY_PATH = resolve(
  ROOT,
  "scripts/generated/play-policy-benchmark.md",
);

export function renderPlayPolicySummary(
  report,
  {
    reportFile = "play-policy-benchmark.json",
  } = {},
) {
  const current = report.policies.current;
  const hybrid = report.policies.hybrid;
  const conservative = report.operativeAggression.conservative;
  const aggressive = report.operativeAggression.aggressive;
  const dynamic = report.operativeAggression.dynamic;
  const italian = report.methodology.language === "it";
  const crossModel = report.methodology.operativeModelId !== "same";
  const title = italian
    ? crossModel
      ? "Italian Play transfer policy benchmark"
      : "Italian Play policy benchmark"
    : crossModel
      ? "Play operative aggression cross-model benchmark"
      : "Play policy benchmark";
  const scope = crossModel
    ? `${report.methodology.model} generated the clues while ${report.methodology.operativeModel} guessed them.`
    : "The clue giver and operative used the same embedding model.";
  const command = italian
    ? crossModel
      ? "npm run benchmark:play:italian-transfer"
      : "npm run benchmark:play:italian"
    : "npm run benchmark:play";
  const modelLine = italian
    ? `- 🤖 Spymaster: ${report.methodology.model}. Operative: ${report.methodology.operativeModel}.\n`
    : "";
  const clueNumbers = [
    ...new Set([
      ...Object.keys(current.clueNumberDistribution),
      ...Object.keys(hybrid.clueNumberDistribution),
    ]),
  ].sort((left, right) => Number(left) - Number(right));
  const remainingCounts = [
    ...new Set([
      ...Object.keys(current.clueNumberByOwnRemaining ?? {}),
      ...Object.keys(hybrid.clueNumberByOwnRemaining ?? {}),
    ]),
  ].sort((left, right) => Number(right) - Number(left));

  return `# ${title}

Latest full-game comparison generated by \`${command}\` on ${report.generatedAt}.

${scope} This is a controlled regression and transfer signal, not a human-realism result.

| 🎯 Policy | 🎉 Fun | 🔢 Multi clues | ⏩ First-half mean | ✅ Correct per turn | 🤝 Close finishes | ☠️ Assassin rate | ⏱️ Turns per game |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
| 🧪 Hybrid | ${decimal(hybrid.fun.score)} | ${percent(hybrid.multiClueRate)} | ${decimal(hybrid.firstHalfMeanClueNumber)} | ${decimal(hybrid.correctCardsPerTurn)} | ${percent(hybrid.closeFinishRate)} | ${percent(hybrid.assassinRate)} | ${decimal(hybrid.meanTurnsPerGame)} |
| 📍 Current | ${decimal(current.fun.score)} | ${percent(current.multiClueRate)} | ${decimal(current.firstHalfMeanClueNumber)} | ${decimal(current.correctCardsPerTurn)} | ${percent(current.closeFinishRate)} | ${percent(current.assassinRate)} | ${decimal(current.meanTurnsPerGame)} |

## 🔎 Operative aggression

Hybrid clue scoring played all three operative modes on the same boards.

| 🔎 Mode | 🧩 Low-sim fill | 🛑 Early pass | 🛟 Forced/game | ✅ Correct per turn | 🔴 Wrong per game | ☠️ Assassin rate | ⏱️ Turns per game |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
| ⚖️ Dynamic | ${percent(dynamic.operativeGuessQuality.weakDeclaredFillRate)} | ${percent(dynamic.operativeGuessQuality.preDeclaredPassRate)} | ${decimal(dynamic.forcedProgressGuessesPerGame)} | ${decimal(dynamic.correctCardsPerTurn)} | ${decimal(dynamic.wrongTeamHitsPerGame)} | ${percent(dynamic.assassinRate)} | ${decimal(dynamic.meanTurnsPerGame)} |
| 🛡️ Conservative | ${percent(conservative.operativeGuessQuality.weakDeclaredFillRate)} | ${percent(conservative.operativeGuessQuality.preDeclaredPassRate)} | ${decimal(conservative.forcedProgressGuessesPerGame)} | ${decimal(conservative.correctCardsPerTurn)} | ${decimal(conservative.wrongTeamHitsPerGame)} | ${percent(conservative.assassinRate)} | ${decimal(conservative.meanTurnsPerGame)} |
| 🚀 Aggressive | ${percent(aggressive.operativeGuessQuality.weakDeclaredFillRate)} | ${percent(aggressive.operativeGuessQuality.preDeclaredPassRate)} | ${decimal(aggressive.forcedProgressGuessesPerGame)} | ${decimal(aggressive.correctCardsPerTurn)} | ${decimal(aggressive.wrongTeamHitsPerGame)} | ${percent(aggressive.assassinRate)} | ${decimal(aggressive.meanTurnsPerGame)} |

Low-sim fill means the guess that reaches the declared clue number had centered cosine similarity below ${dynamic.operativeGuessQuality.weakSimilarityThreshold.toFixed(2)}. It is a diagnostic threshold, not a human judgment.

## 🔢 Clue-number distribution

| 🔢 Clue number | 📍 Current | 🧪 Hybrid |
| --- | ---: | ---: |
${clueNumbers
  .map(
    (number) =>
      `| 🔢 ${number} | ${distributionCell(current, number)} | ${distributionCell(hybrid, number)} |`,
  )
  .join("\n")}

## 🕵️ Clue number by agents left

| 🕵️ Own agents left | 📍 Current mean | 🧪 Hybrid mean | ✅ Hybrid multi available | ⚖️ Hybrid multi edge |
| --- | ---: | ---: | ---: | ---: |
${remainingCounts
  .map((remaining) => {
    const currentStage = current.clueNumberByOwnRemaining?.[remaining];
    const hybridStage = hybrid.clueNumberByOwnRemaining?.[remaining];
    return `| 🔵 ${remaining} | ${optionalDecimal(currentStage?.meanNumber)} | ${optionalDecimal(hybridStage?.meanNumber)} | ${optionalPercent(hybridStage?.multiAvailableRate)} | ${optionalSignedDecimal(hybridStage?.meanBestMultiAdvantage)} |`;
  })
  .join("\n")}

## 📌 Latest outcome

- 🧪 ${report.methodology.boardCount} identical boards, ${current.gameCount + hybrid.gameCount} clue-policy results, ${conservative.gameCount + aggressive.gameCount + dynamic.gameCount} aggression-mode results, and ${report.methodology.candidateCount.toLocaleString("en-US")} clue candidates per turn. Dynamic Hybrid is shared by both comparisons.
${modelLine}- 🎉 Fun Index: ${decimal(current.fun.score)} current and ${decimal(hybrid.fun.score)} hybrid. It balances ambition, momentum, suspense, and flow; human agreement remains a separate guardrail.
- 🌱 Hybrid retried a missed target on ${percent(hybrid.missedTargetRecovery.retryRate)} of eligible clues and ${percent(hybrid.missedTargetRecovery.earlyRetryRate)} while at least four fresh targets remained.
- 🔎 Dynamic accepted ${percent(dynamic.operativeGuessQuality.weakDeclaredFillRate)} low-sim clue-number-filling guesses and passed early on ${percent(dynamic.operativeGuessQuality.preDeclaredPassRate)} of pre-number decisions.
- 🛟 Bounded-simulation guesses after a complete pass round: ${decimal(dynamic.forcedProgressGuessesPerGame)} Dynamic, ${decimal(conservative.forcedProgressGuessesPerGame)} Conservative, and ${decimal(aggressive.forcedProgressGuessesPerGame)} Aggressive per game.
- 🛡️ Conservative changed low-sim clue-number fills by ${signedPercentagePoints(conservative.operativeGuessQuality.weakDeclaredFillRate - dynamic.operativeGuessQuality.weakDeclaredFillRate)} and early passes by ${signedPercentagePoints(conservative.operativeGuessQuality.preDeclaredPassRate - dynamic.operativeGuessQuality.preDeclaredPassRate)} versus Dynamic.
- 🚀 Aggressive changed low-sim clue-number fills by ${signedPercentagePoints(aggressive.operativeGuessQuality.weakDeclaredFillRate - dynamic.operativeGuessQuality.weakDeclaredFillRate)} and early passes by ${signedPercentagePoints(aggressive.operativeGuessQuality.preDeclaredPassRate - dynamic.operativeGuessQuality.preDeclaredPassRate)} versus Dynamic.
- ✅ Hybrid changed multi-card share by ${signedPercentagePoints(report.hybridMinusCurrent.multiClueRate)} and correct cards per turn by ${signedDecimal(report.hybridMinusCurrent.correctCardsPerTurn)}.
- ⏩ Hybrid changed the chronological first-half mean by ${signedDecimal(report.hybridMinusCurrent.firstHalfMeanClueNumber)}.
- 🔴 Hybrid changed wrong-team hits per game by ${signedDecimal(report.hybridMinusCurrent.wrongTeamHitsPerGame)} and assassin rate by ${signedPercentagePoints(report.hybridMinusCurrent.assassinRate)}.
- 🤝 Hybrid changed close finishes by ${signedPercentagePoints(report.hybridMinusCurrent.closeFinishRate)}.
- ⏱️ Hybrid changed turns per game by ${signedDecimal(report.hybridMinusCurrent.meanTurnsPerGame)}.
- ➕ Bonus guesses: ${decimal(current.bonusGuessesPerGame)} per current game at ${percent(current.correctBonusGuessRate)} correct, and ${decimal(hybrid.bonusGuessesPerGame)} per hybrid game at ${percent(hybrid.correctBonusGuessRate)} correct.
- 🛟 Analyzer fallback clues: ${current.fallbackClues} current and ${hybrid.fallbackClues} hybrid.

The full per-game data and methodology are in [${reportFile}](./${reportFile}). Live Play defaults to hybrid clue scoring, late missed-target recovery, and Dynamic operative aggression; setup persists every benchmarked parameter. Same-model self-play is a regression and game-shape signal, not evidence of human realism.
`;
}

export async function writePlayPolicySummary(report, outputPath = DEFAULT_SUMMARY_PATH) {
  const reportFile = basename(outputPath).replace(/\.md$/u, ".json");
  await writeFile(outputPath, renderPlayPolicySummary(report, { reportFile }));
}

function distributionCell(policy, number) {
  const count = policy.clueNumberDistribution[number] ?? 0;
  return `${count.toLocaleString("en-US")} (${percent(count / policy.clueCount)})`;
}

function percent(value) {
  return `${(value * 100).toFixed(1)}%`;
}

function decimal(value) {
  return value.toFixed(2);
}

function optionalDecimal(value) {
  return Number.isFinite(value) ? decimal(value) : "N/A";
}

function optionalPercent(value) {
  return Number.isFinite(value) ? percent(value) : "N/A";
}

function optionalSignedDecimal(value) {
  return Number.isFinite(value) ? signedDecimal(value) : "N/A";
}

function signedDecimal(value) {
  return `${value >= 0 ? "+" : ""}${decimal(value)}`;
}

function signedPercentagePoints(value) {
  return `${value >= 0 ? "+" : ""}${(value * 100).toFixed(1)} percentage points`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const reportPath = resolve(process.argv[2] ?? DEFAULT_REPORT_PATH);
  const outputPath = resolve(process.argv[3] ?? DEFAULT_SUMMARY_PATH);
  const report = JSON.parse(await readFile(reportPath, "utf8"));
  await writePlayPolicySummary(report, outputPath);
  console.log(`Wrote ${outputPath}`);
}
